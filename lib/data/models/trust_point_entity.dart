// lib/models/place.dart
// =============================================================================
// Модель данных одной точки «Пункта доверия» на карте.
// =============================================================================
//
// Чистый Dart — никаких Flutter-виджетов и внешних зависимостей, кроме
// latlong2 (нужна только для типа LatLng).
// =============================================================================

import 'package:latlong2/latlong.dart';

/// Описание одного «Пункта доверия» — точки на карте.
///
/// Все поля [final]: объект создаётся один раз из константного списка
/// и не мутируется. Flutter эффективно сравнивает такие объекты.
class Place {
  /// Уникальный строковый идентификатор (используется как ключ в [ValueKey]).
  final String id;

  /// Отображаемое название учреждения.
  final String name;

  /// Тип учреждения — определяет цвет и иконку маркера на карте.
  final PlaceCategory category;

  /// Адрес одной строкой — показывается в карточке под названием.
  final String address;

  /// Режим работы, например «08:00–18:00» или «09:00–17:00».
  final String hours;

  /// Перечень услуг, оказываемых в данной точке.
  ///
  /// Хранится как [List<String>], чтобы можно было рендерить каждый пункт
  /// отдельно (чипами или маркированным списком) без лишнего парсинга.
  final List<String> services;

  /// Географические координаты (широта/долгота) в формате [LatLng]
  /// из пакета latlong2 — именно этот тип ожидает flutter_map.
  final LatLng location;

  const Place({
    required this.id,
    required this.name,
    required this.category,
    required this.address,
    required this.hours,
    required this.services,
    required this.location,
  });
}

/// Категория пункта доверия.
///
/// Определяет визуальное оформление маркера (цвет, иконка) и
/// заголовок типа в карточке деталей.
enum PlaceCategory {
  /// Городская поликлиника с базовым набором услуг.
  polyclinic,

  /// Кожно-венерологический диспансер.
  dermatoVenerologic,

  /// Центр по профилактике и борьбе со СПИД.
  aidsCenter,
}